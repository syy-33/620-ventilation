"""Run the logic checks in simulation and write docs/sim_results.md.

This exercises the alarm and detection logic against a modelled rig across a
range of sensor response times. It is evidence that the *logic* meets its
requirements given a known signal. It is NOT evidence about the hardware: the
bench verification in docs/07_verification_report.md is still required.

    python tools/run_sim_verification.py
"""

from datetime import date
from pathlib import Path

import numpy as np

from capno_analysis import fault_eval
from capno_analysis.data import from_records
from capno_core.capability import captured_fraction, loss_alarm_latency_s, max_resolvable_rr
from capno_sim.run import records
from capno_sim.scenarios import SCENARIOS, steady

ROOT = Path(__file__).resolve().parent.parent
RESPONSE_TIMES = [0.3, 1.0, 2.0, 5.0]
DELAY = 1.5


def fs_for(t):
    return 2.0 if t >= 5 else 20.0


def rate_table():
    lines = ["| t10-90 (s) | breath-by-breath limit (/min) | true RR | measured RR | peak shown / true EtCO2 | model prediction | label shown |",
             "|---|---|---|---|---|---|---|"]
    for t in RESPONSE_TIMES:
        lim = max_resolvable_rr(t)
        for rr in (6, 12, 20, 30):
            recs = list(records(steady(rr=rr, et=5.0, seconds=150), t, DELAY, fs_for(t)))
            st = [r for r in recs if r["type"] == "st"][-1]
            shown = "—" if st["et"] is None else f"{st['et'] / 5.0:.2f}"
            lines.append(f"| {t} | {lim:.1f} | {rr} | {st['rr'] if st['rr'] is not None else '—'} |"
                         f" {shown} | {captured_fraction(rr, t):.2f} | {st['et_kind']}"
                         f"{', ' + st['rr_note'] if st['rr_note'] else ''} |")
    return "\n".join(lines)


def fault_table():
    lines = ["| t10-90 (s) | segments | critical sensitivity | critical specificity | technical sensitivity | faults shown as critical | false alarms in normal | disconnect latency median / max (s) | published worst case (s) |",
             "|---|---|---|---|---|---|---|---|---|"]
    for t in RESPONSE_TIMES:
        run = from_records(records(SCENARIOS["fault_dataset"](), t, DELAY, fs_for(t)))
        s = fault_eval.summarise(fault_eval.evaluate(run))
        lat = s["latency_s"].get("disconnect", {})
        bound = loss_alarm_latency_s(DELAY, t, 20.0)
        lines.append(f"| {t} | {s['segments']} | {s['critical_sensitivity']} | {s['critical_specificity']} |"
                     f" {s['technical_sensitivity']} | {s['faults_presented_as_critical']} |"
                     f" {s['false_alarms_in_normal']} | {lat.get('median', '—')} / {lat.get('max', '—')} |"
                     f" {bound:.1f} |")
    return "\n".join(lines)


def scenario_table():
    lines = ["| scenario | t10-90 (s) | alarm and technical events (time from start, s) |", "|---|---|---|"]
    for name in ("figure2", "oesophageal", "no_co2", "blocked_line", "open_line", "sensor_silent",
                 "apnoea", "bradypnoea"):
        for t in (0.3, 5.0):
            recs = records(SCENARIOS[name](), t, DELAY, fs_for(t))
            ev = []
            for r in recs:
                if r["type"] == "e" and r["kind"] in ("alarm", "technical", "monitor"):
                    what = r["to"] or ("cleared " + str(r["from"]))
                    ev.append(f"{r['t'] / 1000:.1f} {what}" + (f" ({r['reason']})" if r["kind"] == "alarm" else ""))
            lines.append(f"| {name} | {t} | {'; '.join(ev)} |")
    return "\n".join(lines)


def main():
    out = ROOT / "docs" / "sim_results.md"
    body = f"""# Simulation results (logic verification only)

Generated by `python tools/run_sim_verification.py` on {date.today().isoformat()}.

**These are not bench results.** The simulator (capno_sim) models the airway,
a sampling line with {DELAY} s transport delay and a first-order NDIR sensor.
The tables show that the detection and alarm logic in capno_core does what the
engineering requirements say *for that model*, across a range of sensor
speeds. Whether the real sensor, line and pump behave like the model is what
VP-5 and VP-5b on the bench decide.

## 1. Breathing rate and end-tidal capture versus sensor speed (ER-4, ER-5)

{rate_table()}

Two things to read from this table. First, the square-wave model behind the
published limit is optimistic: with a realistic capnogram shape (sloped
alveolar plateau, finite upstroke) the shown peak is 1-9 points lower than
the model predicts. That is why VP-5b checks the published limit against the
reference capnograph and derates it if they disagree. Second, the rate
survives a slow sensor much better than the end-tidal value does:
the breath detector only needs a swing, while the peak needs the sensor to
settle. This is why the device labels end-tidal values as *attenuated* or
*trend* above the published breath-by-breath limit instead of hiding the
problem.

## 2. Labelled fault dataset (ER-2, ER-3)

Scenario `fault_dataset`: five cycles of blocked line, circuit disconnection,
line open at the monitor, apnoea and sensor silence, separated by normal
breathing at 12-20 /min.

{fault_table()}

## 3. Scenario event sequences (ER-1 to ER-4)

{scenario_table()}
"""
    out.write_text(body)
    print("wrote", out)


if __name__ == "__main__":
    np.seterr(all="ignore")
    main()
